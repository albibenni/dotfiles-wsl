local map = vim.keymap.set
map("n", "<Esc>", "<cmd>nohlsearch<cr>")
map("v", "J", ":m '>+1<CR>gv=gv", { desc = "Move selection down" })
map("v", "K", ":m '<-2<CR>gv=gv", { desc = "Move selection up" })
map("n", "J", "mzJ`z")
map("n", "H", "<C-w>h")
map("n", "L", "<C-w>l")
for _, key in ipairs({ "h", "j", "k", "l" }) do map("n", "<C-" .. key .. ">", "<C-w>" .. key) end
map("n", "<C-d>", "<C-d>zz")
map("n", "<C-u>", "<C-u>zz")
map("n", "n", "nzzzv")
map("n", "N", "Nzzzv")
map("x", "<leader>p", [["_dP]], { desc = "Paste without replacing register" })
map({ "n", "v" }, "<leader>d", [["_d]], { desc = "Delete without replacing register" })
map({ "n", "v" }, "<leader>y", [["+y]], { desc = "Copy to Windows clipboard" })
map("n", "<leader>Y", [["+Y]])
map("i", "<C-c>", "<Esc>")
map("n", "Q", "<nop>")
map("n", "<leader>k", "<cmd>lnext<cr>zz")
map("n", "<leader>j", "<cmd>lprev<cr>zz")
map("n", "<leader>vs", "<cmd>vsplit<cr>", { desc = "Vertical split" })
map("n", "<leader>rp", [[:%s/\<<C-r><C-w>\>/<C-r><C-w>/gI<Left><Left><Left>]], { desc = "Replace current word" })
map("n", "<leader>xx", function()
    local file = vim.api.nvim_buf_get_name(0)
    if file ~= "" then
        local output = vim.fn.system({ "chmod", "+x", file })
        if vim.v.shell_error ~= 0 then vim.notify(output, vim.log.levels.ERROR) end
    end
end, { desc = "Make current file executable" })
map("n", "<leader>vpp", function() vim.cmd.edit(vim.g.dotfiles_wsl_root .. "/config/nvim/lua/wsl/plugins") end, { desc = "Edit plugins" })
map("n", "<leader>vpk", function() vim.cmd.edit(vim.g.dotfiles_wsl_root .. "/config/nvim/lua/wsl/keymaps.lua") end, { desc = "Edit keymaps" })
map("n", "<leader>w", "<cmd>write<cr>", { desc = "Write buffer" })
map("n", "<leader>ts", function() vim.opt_local.spell = not vim.opt_local.spell:get() end, { desc = "Toggle spellcheck" })
map("n", "<leader>q", vim.diagnostic.setloclist, { desc = "Diagnostic location list" })
map("n", "<leader>vd", vim.diagnostic.open_float, { desc = "Diagnostic details" })
map("n", "[d", function() vim.diagnostic.jump({ count = -1, float = true }) end)
map("n", "]d", function() vim.diagnostic.jump({ count = 1, float = true }) end)
map("i", "<C-h>", vim.lsp.buf.signature_help, { desc = "Signature help" })
map("n", "<C-f>", function() require("wsl.sessionizer").pick() end, { desc = "Tmux project picker" })
map("n", "<leader>tr", function() vim.cmd.colorscheme("tokyonight-night") end, { desc = "Reload theme" })
